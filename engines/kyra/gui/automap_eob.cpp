template void Automap_EoB::drawIconImpl<uint16>(Graphics::Surface&, int, int, int, int, int, IconAlignment, int, int, int);
template void Automap_EoB::drawIconImpl<uint32>(Graphics::Surface&, int, int, int, int, int, IconAlignment, int, int, int);

int Automap_EoB::fitString(const Graphics::Font *f, const Common::String &str, int maxW, int maxSc) const {
	Common::U32String u32str(str.c_str(), Common::CodePage::kUtf8);
	int wdth = f ? f->getStringWidth(u32str) : 0;
	return (wdth == 0) ? 0 : CLIP<int>(maxW / wdth, 0, maxSc);
}

uint16 Automap_EoB::calcNewBlockPosition(uint16 block, int8 dir) const {
	const int16 blockPosTable[] = { -32, 1, 32, -1 };
	return (block + blockPosTable[dir & 3]) & 0x3FF;
}

bool Automap_EoB::isVisited(uint16 block) const {
	assert(block < 1024);
	return (_blockData[block].direction & 2) != 0;
}

bool Automap_EoB::isSeen(uint16 block) const {
	assert(block < 1024);
	return (_blockData[block].direction & 1) != 0;
}

int Automap_EoB::checkForBreakableObjectType(uint16 block) const {
	LevelBlockProperty &bp = _blockData[block];

	// Scripted types: most things in EOBII, like the barrels in the catacombs, the glass walls, the sealed 4 horns door, etc.
	// The scripts may require specific items to be used, like the green hammer, the 4 horns, etc. 
	bool breakableType = (bp.flags & 0x800);

	if (!breakableType) {
		// Non-scripted types: walls that can just be destroyed by a weapon, like the spider webs in the EOBII catacombs. Any
		// close-combat weapon can be used.
		for (int i = 0; i < 4 && !breakableType; ++i) {
			if (_specialWallTypes[bp.walls[i]] == 0xFF)
				breakableType = true;
		}
	}

	if (!breakableType)
		return kNoBreakableObject;

	// Determine from the room layout whether it is a door-like barrier.
	for (int i = 0; i < 2; ++i) {
		if (!(_wllWallFlags[bp.walls[i]] & 1) && !(_wllWallFlags[bp.walls[i ^ 2]] & 1) &&
			(_wllWallFlags[_blockData[calcNewBlockPosition(block, i)].walls[i ^ 2]] & 1) && (_wllWallFlags[_blockData[calcNewBlockPosition(block, i ^ 2)].walls[i]] & 1) &&
				!(_wllWallFlags[_blockData[calcNewBlockPosition(block, i ^ 1)].walls[i ^ 3]] & 1) && !(_wllWallFlags[_blockData[calcNewBlockPosition(block, i ^ 3)].walls[i ^ 1]] & 1))
					return kBreakableBarrierNS + i;
	}

	if (!(bp.flags & 0x800))
		return kNoBreakableObject;

	// Breakable objects (like the barrels in the EOBII catacombsvor the mantis eggs in the silver tower). Check if it is accessible/interactive from multiple sides.
	int cn = 0;	
	for (int i = 0; i < 4; ++i) {
		if (!(_wllWallFlags[bp.walls[i]] & 1) && _specialWallTypes[bp.walls[i]] == 8)
			++cn;
	}
	if (cn >= 2)
		return kBreakableBlockObject;

	// Unfortunately, some breakable objects don't get processed completely by the scripts after being broken. This can lead to glitchy drawing. So we try to figure out
	// here if it is a broken barrier and report that...
	cn = 0;
	for (int i = 0; i < 4; ++i) {
		if (!(_wllWallFlags[bp.walls[i]] & 1))
			++cn;
	}
	if (cn < 4)
		return kBrokenBarrier;

	return kNoBreakableObject;
}

bool Automap_EoB::isCenteredSwitch(uint16 block) const {
	LevelBlockProperty &bp = _blockData[block];

	int cn = 0;
	for (int i = 0; i < 4; ++i) {
		uint8 ww = bp.walls[i];
		if ((_wllWallFlags[ww] & 1) && _specialWallTypes[ww] == 3)
			++cn;
	}
	return (cn > 1);
}

int EoBCoreEngine::clickedAutomap(Button *button) {
	gui_updateControls();
	removeInputTop();
	disableSysTimer(2);

	txt()->removePageBreakFlag();
	_screen->copyRegion(0, 120, 0, 0, 176, 48, 0, Screen_EoB::kCampMenuBackupPage, Screen::CR_NO_P_CHECK);

	for (int i = 0; i < 6; i++) {
		if (!testCharacter(i, 1))
			continue;
		_characters[i].damageTaken = 0;
		_characters[i].slotStatus[0] = _characters[i].slotStatus[1] = 0;
		gui_drawCharPortraitWithStats(i);
	}

	bool update = true;
	bool firstPage = true;
	int currentLevel = _currentLevel;
	int currentSub = _currentSub;
	int currentBlock = _currentBlock;
	int currentDirection = _currentDirection;
	int numLevels = (_flags.gameID == GI_EOB2) ? 16 : 12;
	const uint8 partyIconBlinkSpeed = 100;
	uint32 partyIconBlinkTimer = _system->getMillis() + partyIconBlinkSpeed;

	int ow = _system->getOverlayWidth();
	int oh = _system->getOverlayHeight();

	_automap->markSeen(_currentBlock, _currentDirection);
	_automap->markVisited(_currentBlock);

	_system->showOverlay();

	for (bool runLoop = true; runLoop && !shouldQuit();) {
		uint32 frameEnd = _system->getMillis() + 8;

		int inputFlag = checkInput(nullptr, false, 0) & 0x80FF;	// TODO? We could allow GMM loading on the map screen, but it would require some post-processing
		removeInputTop();

		// restore overlay if the GMM or the debugger has been used on the map screen
		if (!_system->isOverlayVisible()) {
			_system->showOverlay();
			update = true;
		}

		// redraw map if the window has been resized
		if (ow != _system->getOverlayWidth() || oh != _system->getOverlayHeight()) {
			ow = _system->getOverlayWidth();
			oh = _system->getOverlayHeight();
			update = true;
		}

		int lvl = _currentLevel;

		if (inputFlag == _keyMap[Common::KEYCODE_ESCAPE] || inputFlag == _keyMap[Common::KEYCODE_TAB]) {
			runLoop = false;
		} else if (inputFlag == _keyMap[Common::KEYCODE_UP]) {
			for (int i = lvl; lvl == _currentLevel && i <= numLevels; ++i) {
				if (_hasTempDataFlags & (1 << (i - 1)))
					lvl = i;
			}
		} else if (inputFlag == _keyMap[Common::KEYCODE_DOWN]) {
			for (int i = lvl; lvl == _currentLevel && i > 0; --i) {
				if (_hasTempDataFlags & (1 << (i - 1)))
					lvl = i;
			}
		}

		if (lvl != _currentLevel) {
			if (firstPage) {
				completeDoorOperations();
				generateTempData();
				firstPage = false;
			}

			loadLevel(lvl, 0);

			_currentBlock = (currentLevel == lvl) ? currentBlock : 0xFFFF;
			update = true;
		}

		if (update) {
			_automap->draw(_currentLevel, _currentBlock, _currentDirection);
			update = false;
		} else if (_currentBlock != 0xFFFF) {
			if (_system->getMillis() > partyIconBlinkTimer) {
				_automap->drawPartyIcon(_currentBlock, _currentDirection);
				partyIconBlinkTimer = _system->getMillis() + partyIconBlinkSpeed;
			}
		}

		delayUntil(frameEnd, false, false, false); // TODO? allow GMM loading on the map screen, seen comment above
	}

	if (currentLevel != _currentLevel || currentSub != _currentSub)
		loadLevel(currentLevel, currentSub);

	_currentBlock = currentBlock;
	_currentDirection = currentDirection;

	_system->hideOverlay();

	if (_flags.platform == Common::kPlatformSegaCD) {
		setLevelPalettes(_currentLevel);
		_screen->sega_selectPalette(-1, 2, true);
		gui_setupPlayFieldHelperPages(true);
		gui_drawAllCharPortraitsWithStats(false);
	}

	drawScene(0);

	_screen->setCurPage(0);
	const ScreenDim *dm = _screen->getScreenDim(10);
	_screen->copyRegion(0, 0, 0, 120, 176, 48, Screen_EoB::kCampMenuBackupPage, 2, Screen::CR_NO_P_CHECK);
	_screen->copyRegion(dm->sx << 3, dm->sy, dm->sx << 3, dm->sy, dm->w << 3, dm->h, 2, 0, Screen::CR_NO_P_CHECK);

	_screen->updateScreen();

	enableSysTimer(2);
	advanceTimers(_restPartyElapsedTime);
	_restPartyElapsedTime = 0;

	checkPartyStatus(true);

	return button->arg;
}

