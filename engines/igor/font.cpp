int Font::getCharWidth(uint32 chr) const {
	if (chr == ' ') {
		return 5;
	}
	if (chr >= 256) {
		return 0;
	}
	int idx = _charIndex[chr];
	if (idx == 99) {
		return 0;
	}
	return _charWidth[idx];
}

