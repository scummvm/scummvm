void DungeonMap::dungeonDrawCell(int distance, int x, int y) {
	const Data::DungeonCell cell = cellAt(x, y);

	if (cell._monsterId != Data::DUNGEON_NO_MONSTER) {
		if (cell._tileNum == Data::DTILE_DOOR || cell._tileNum == Data::DTILE_SECRET_DOOR ||
				cell._tileNum == Data::DTILE_WALL)
			drawWall(distance);

		// A monster sharing a ladder's cell only gets the "hole" opening
		// drawn, not the full shaft - matching the original's dungeonDrawCell2
		if (cell._tileNum == Data::DTILE_LADDER_DOWN)
			dungeonDrawWidget(LADDER_DOWN_TOP_DATA, distance + 1, EDGE_COLOR);
		else if (cell._tileNum == Data::DTILE_LADDER_UP)
			dungeonDrawWidget(LADDER_UP_TOP_DATA, distance + 1, EDGE_COLOR);

		dungeonDrawMonster(cell._monsterId, distance);
		return;
	}

	bool facingUpDown = _G(savegame)._dungeonDirection == Data::DIR_UP ||
		_G(savegame)._dungeonDirection == Data::DIR_DOWN;

	switch (cell._tileNum) {
	case Data::DTILE_WALL:
	case Data::DTILE_SECRET_DOOR:
		drawWall(distance);
		break;
	case Data::DTILE_DOOR:
		drawDoorway(distance);
		break;
	case Data::DTILE_LADDER_DOWN:
		if (facingUpDown)
			drawLadderDownFaceOn(distance + 1);
		else
			drawLadderDownSideways(distance + 1);
		break;
	case Data::DTILE_LADDER_UP:
		if (facingUpDown)
			drawLadderUpFaceOn(distance + 1);
		else
			drawLadderUpSideways(distance + 1);
		break;
	case Data::DTILE_BEAMS:
		drawBeams(distance);
		break;
	default:
		break;
	}

	if (cell._itemId == Data::DITEM_COFFIN)
		drawCoffin(distance + 1);
	else if (cell._itemId == Data::DITEM_CHEST)
		drawChest(distance + 1);
}

void DungeonMap::dungeonDrawWidget(const uint8 *data, int distance, int color) {
	// Distance-1, clamped to 0-4 via an unsigned comparison, so a distance
	// of 0 (the player's own cell) wraps around and also clamps to 4
	int tier = distance - 1;
	if ((uint)tier > 4)
		tier = 4;

	// The farthest tier gets shrunk down one extra bit beyond the others
	int bitShift = (tier == 4) ? tier + 1 : tier;
	int offsetY = UWIDGET_OFFSET_Y[tier];

	auto s = getSurface();
	Common::Point pen;
	int idx = 0;

	for (;;) {
		int8 val = data[idx++];
		if (val == 127)
			break;

		bool moveTo = (val == 126);
		int8 xByte = moveTo ? data[idx++] : val;
		int8 yByte = data[idx++];

		int x = (xByte >> bitShift) + 160;
		int y = (yByte >> bitShift) + offsetY;

		if (moveTo) {
			pen = Common::Point(x, y);
		} else {
			s.drawLine(pen.x, pen.y, x, y, color);
			pen = Common::Point(x, y);
		}
	}
}

void DungeonMap::drawCoffin(int distance) {
	// TODO: show "Coffin" in the commands area (writeStringNewline in the
	// original) - that belongs to DungeonLogic, as with monster names
	dungeonDrawWidget(COFFIN_DRAW_DATA, distance, EDGE_COLOR);
}

void DungeonMap::drawChest(int distance) {
	// TODO: show "Chest" in the commands area (writeStringNewline in the
	// original) - that belongs to DungeonLogic, as with monster names.
	// Reuses the mimic's widget shape, since the original draws chests and
	// mimics identically
	dungeonDrawWidget(UWIDGET_DRAW_TABLE[UMONS_MIMIC], distance, EDGE_COLOR);
}

void DungeonMap::dungeonDrawMonster(int monsterId, int distance) {
	if (distance >= 5)
		return;

	// TODO: show the monster's name in the commands area (writeStringNewline
	// with UNDERWORLD_MONSTERS[monsterId] in the original) - that belongs
	// to DungeonLogic, once it exists there

	if (monsterId == UMONS_GELATINOUS_CUBE) {
		// The cube fills the whole passage rather than using a widget shape
		drawWall(distance);
		drawLeftEdge(distance);
		drawRightEdge(distance);
	} else {
		dungeonDrawWidget(UWIDGET_DRAW_TABLE[monsterId], distance, EDGE_COLOR);
	}
}

void DungeonMap::drawDungeonView() {
	const auto &pos = _G(savegame)._locationPosition;

	int deltaX = getDirDeltaX();
	int deltaY = getDirDeltaY();

	int leftDeltaX = 0, leftDeltaY = 0, rightDeltaX = 0, rightDeltaY = 0;
	switch (_G(savegame)._dungeonDirection) {
	case Data::DIR_UP:
		leftDeltaX = -1;
		rightDeltaX = 1;
		break;
	case Data::DIR_DOWN:
		leftDeltaX = 1;
		rightDeltaX = -1;
		break;
	case Data::DIR_RIGHT:
		leftDeltaY = -1;
		rightDeltaY = 1;
		break;
	case Data::DIR_LEFT:
		leftDeltaY = 1;
		rightDeltaY = -1;
		break;
	default:
		break;
	}

	auto s = getSurface();
	s.fillRect(TextRect(1, 1, 38, 18), 0);
	drawFacingDirection();

	const Data::DungeonCell ownCell = cellAt(pos.x, pos.y);
	bool isDoor = ownCell._tileNum == Data::DTILE_DOOR;
	bool isWall = ownCell._tileNum == Data::DTILE_SECRET_DOOR || ownCell._tileNum == Data::DTILE_WALL;

	int distance = distanceToOccupiedCell(deltaX, deltaY);

	if (isWall) {
		drawWall(0);
		return;
	}

	int index = distance;
	int backX = deltaX * index, backY = deltaY * index;
	int currDeltaX = backX, currDeltaY = backY;
	bool skipToEnd = false;

	if (isDoor) {
		// A secret door diagonally adjacent while standing in a doorway
		// forces an immediate wall, skipping the rest of the view
		int t1 = cellAt(pos.x + leftDeltaX, pos.y + leftDeltaY)._tileNum;
		int t2 = cellAt(pos.x + leftDeltaX, pos.y + deltaY)._tileNum;
		if (t1 != Data::DTILE_WALL && t1 != Data::DTILE_DOOR && t2 == Data::DTILE_SECRET_DOOR) {
			drawWall(0);
			skipToEnd = true;
		}
	}

	if (!skipToEnd) {
		if (isDoor)
			drawDoorway(0);

		bool endingLeft = false, endingRight = false;
		bool leftSolid = false, rightSolid = false;

		while (index > 0) {
			currDeltaX -= deltaX;
			currDeltaY -= deltaY;

			// Skip re-deriving the flanking walls for the innermost tier
			// when standing in a doorway - already handled above
			if (!(isDoor && index == 1)) {
				int currX = pos.x + currDeltaX;
				int currY = pos.y + currDeltaY;
				int leftTile = cellAt(currX + leftDeltaX, currY + leftDeltaY)._tileNum;
				int rightTile = cellAt(currX + rightDeltaX, currY + rightDeltaY)._tileNum;

				drawLeftCell(index, leftTile);
				drawRightCell(index, rightTile);

				bool newLeftSolid = isSolidTile(leftTile);
				bool newRightSolid = isSolidTile(rightTile);

				if (index == distance) {
					endingLeft = newLeftSolid;
					endingRight = newRightSolid;
				} else {
					if (leftSolid != newLeftSolid)
						drawLeftEdge(index);
					if (rightSolid != newRightSolid)
						drawRightEdge(index);
				}

				leftSolid = newLeftSolid;
				rightSolid = newRightSolid;
			}

			int xp = pos.x + currDeltaX + deltaX;
			int yp = pos.y + currDeltaY + deltaY;
			dungeonDrawCell(index, xp, yp);

			--index;
		}

		if (!isDoor)
			dungeonDrawCell(0, pos.x, pos.y);

		int backTileNum = cellAt(pos.x + backX, pos.y + backY)._tileNum;
		if (isMonsterBlocking(pos.x + backX, pos.y + backY) && backTileNum != Data::DTILE_DOOR && distance < 5) {
			// A monster is blocking the view just past the last drawn
			// tier, so cap the view with one more tier right behind it
			int leftTile = cellAt(pos.x + leftDeltaX + backX, pos.y + leftDeltaY + backY)._tileNum;
			int rightTile = cellAt(pos.x + rightDeltaX + backX, pos.y + rightDeltaY + backY)._tileNum;

			drawLeftCell(distance + 1, leftTile);
			drawRightCell(distance + 1, rightTile);

			if (!isSolidTile(leftTile))
				drawLeftEdge(distance);
			if (!isSolidTile(rightTile))
				drawRightEdge(distance);

		} else {
			if (endingLeft)
				drawLeftEdge(distance);
			if (endingRight)
				drawRightEdge(distance);
		}
	}

	if (isDoor) {
		if (ownCell._itemId == Data::DITEM_COFFIN)
			drawCoffin(1);
		else if (ownCell._itemId == Data::DITEM_CHEST)
			drawChest(1);
	}
}

