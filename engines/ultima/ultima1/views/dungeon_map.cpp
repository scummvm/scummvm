Data::DungeonCell DungeonMap::cellAt(int x, int y) const {
	if (x < 0 || x >= Data::DUNGEON_WIDTH || y < 0 || y >= Data::DUNGEON_HEIGHT)
		return Data::DungeonCell{ Data::DTILE_WALL, Data::DUNGEON_NO_MONSTER, Data::DITEM_NONE, 0 };

	return _G(dungeon)._cells[y][x];
}

int DungeonMap::getDirDeltaX() const {
	switch (_G(savegame)._dungeonDirection) {
	case Data::DIR_RIGHT:
		return 1;
	case Data::DIR_LEFT:
		return -1;
	default:
		return 0;
	}
}

int DungeonMap::getDirDeltaY() const {
	switch (_G(savegame)._dungeonDirection) {
	case Data::DIR_UP:
		return -1;
	case Data::DIR_DOWN:
		return 1;
	default:
		return 0;
	}
}

bool DungeonMap::isMonsterBlocking(int x, int y) const {
	int monsterId = cellAt(x, y)._monsterId;
	if (monsterId == Data::DUNGEON_NO_MONSTER)
		return false;

	return monsterId != UMONS_GELATINOUS_CUBE && monsterId != UMONS_MIMIC &&
		monsterId != UMONS_INVISIBLE_SEEKER;
}

bool DungeonMap::isCellOccupied(int deltaX, int deltaY) const {
	const auto &pos = _G(savegame)._locationPosition;
	int x = pos.x + deltaX, y = pos.y + deltaY;

	int tile = cellAt(x, y)._tileNum;
	if (tile == Data::DTILE_WALL || tile == Data::DTILE_SECRET_DOOR || tile == Data::DTILE_DOOR)
		return true;

	return isMonsterBlocking(x, y);
}

static int sgn(int val) {
	return (val > 0) ? 1 : (val < 0 ? -1 : 0);
}

int DungeonMap::distanceToOccupiedCell(int deltaX, int deltaY) const {
	int dx = deltaX, dy = deltaY;
	int idx = 1;

	while (!isCellOccupied(dx, dy)) {
		++idx;
		dx += sgn(deltaX);
		dy += sgn(deltaY);
	}

	return MIN(idx, 5);
}

bool DungeonMap::isSolidTile(int tileNum) const {
	return tileNum != Data::DTILE_HALLWAY && tileNum != Data::DTILE_LADDER_UP &&
		tileNum != Data::DTILE_LADDER_DOWN && tileNum != Data::DTILE_BEAMS;
}

