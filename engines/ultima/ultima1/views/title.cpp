constexpr int FLAGS_WIDTH = 24;
constexpr int FLAGS_HEIGHT = 8;
static const byte FLAGS_BITS[] = {
	0x00,0x00,0x18,0x00,0x00,0x0c,0x00,0x03,0x07,0x01,0x3f,0x01,0x07,0x03,0x00,
	0x0c,0x00,0x00,0x18,0x00,0x00,0x00,0x00,0x00
};

// In XBM images, 0 is white and 1 is black. We need to remap this to the order required by the engine.
static const uint32  LOGO_MAP[] = { 1,  0 };
static const uint32 FLAGS_MAP[] = { 11, 10 };

// Raw LFSR steps taken per draw() call while revealing the logo. Most are
// discarded (see revealLogoPixels), so this is much larger than the
// number of pixels actually drawn per call
constexpr int LOGO_STEPS_PER_FRAME = 4000;

// Number of lines drawn from the top and bottom on the credits screen
// before they meet in the middle (half the logo's 64-pixel height)
constexpr int CREDITS_LOGO_LINES = 32;

// Lines revealed per draw() call from each end - 2 rather than 1 doubles
// the reveal speed versus the original
constexpr int CREDITS_LOGO_STEP = 2;


Title::Title() : View("Title") {
}

bool Title::msgFocus(const FocusMessage &msg) {
	// Load images for display
	Image::XBMDecoder logo;
	if (!logo.loadBits(LOGO_BITS, LOGO_WIDTH, LOGO_HEIGHT))
		error("Could not load logo");
	const Graphics::Surface *src = logo.getSurface();
	_logo.create(src->w, src->h);
	Graphics::crossBlitMap((byte *)_logo.getPixels(), (const byte *)src->getPixels(),
		_logo.pitch, src->pitch, _logo.w, _logo.h, _logo.format.bytesPerPixel, LOGO_MAP);

	Image::XBMDecoder flags;
	if (!flags.loadBits(FLAGS_BITS, FLAGS_WIDTH, FLAGS_HEIGHT))
		error("Could not load flags");
	src = flags.getSurface();
	for (int idx = 0; idx < 3; ++idx) {
		_flags[idx].create(8, 8);
		Graphics::crossBlitMap((byte *)_flags[idx].getPixels(), (const byte *)src->getBasePtr(idx * 8, 0),
			_flags[idx].pitch, src->pitch, _flags[idx].w, _flags[idx].h, _flags[idx].format.bytesPerPixel, FLAGS_MAP);
	}

	Gfx::PicDecoder decoder;
	Common::File f;
	if (!f.open("castle.16") || !decoder.loadStream(f))
		error("Could not load castle.16");
	_castle.create(320, 200);
	_castle.blitFrom(*decoder.getSurface());
	_castlePalette = decoder.getPalette();

	_state = PRESENTS;
	resetLogoReveal();
	delayFrames(1);
	return View::msgFocus(msg);
}

bool Title::msgUnfocus(const UnfocusMessage &msg) {
	// Free surfaces
	_logo.free();
	for (int i = 0; i < 3; ++i)
		_flags[i].free();
	_castle.free();

	return View::msgUnfocus(msg);
}

void Title::draw() {
	auto s = getSurface();

	// The castle picture uses its own custom palette (see PicDecoder);
	// every other state uses the engine's standard EGA palette
	if (_state != CASTLE)
		g_system->getPaletteManager()->setPalette(Graphics::Palette::createEGAPalette());

	switch (_state) {
	case PRESENTS:
		// Only clear on the very first frame - the reveal builds up the
		// logo incrementally across many draw() calls, so the screen
		// must be left alone in between
		if (_logoPixelsDrawn == 0)
			s.clear();

		if (_logoPixelsDrawn < _logo.w * _logo.h) {
			revealLogoPixels(s);
		} else {
			s.setColor(COLOR_TEXT);
			s.writeString(Common::Point(14, 13), "Presents...");
		}
		break;

	case INTRO_A:
		s.clear();
		s.blitFrom(_logo, Common::Point(20, 21));
		s.setColor(COLOR_TEXT);
		s.writeString(Common::Point(5, 12), "...a new release of the best");
		s.writeString(Common::Point(5, 13), "   selling personal computer");
		s.writeString(Common::Point(5, 14), "   role-playing adventure...");
		break;

	case INTRO_B:
		s.clear();
		s.blitFrom(_logo, Common::Point(20, 21));
		s.setColor(COLOR_TEXT);
		s.writeString(Common::Point(6, 12), "...Lord British's original");
		s.writeString(Common::Point(6, 13), "   fantasy masterpiece...");
		break;

	case CASTLE:
		g_system->getPaletteManager()->setPalette(_castlePalette);
		s.blitFrom(_castle);
		drawCastleFlag(s, FLAG_X1);
		drawCastleFlag(s, FLAG_X2);
		break;

	case CREDITS:
		// Only clear on the very first frame - the logo slides in from
		// the top and bottom incrementally across many draw() calls
		if (_creditsLine == 0)
			s.clear();

		if (_creditsLine < CREDITS_LOGO_LINES) {
			drawCreditsLogo(s);
		} else {
			s.setColor(COLOR_FOREGROUND);
			s.writeString(Common::Point(1, 17), "ULTIMA and LORD BRITISH are registered");
			s.writeString(Common::Point(2, 18), "trademarks of Richard Garriott and");
			s.writeString(Common::Point(11, 19), "Origin Systems, Inc.");
			s.writeString(Common::Point(6, 23), "Conversion by: John Fachini");
		}
		break;
	}
}

void Title::resetLogoReveal() {
	_logoPixelsDrawn = 0;
	_logoLfsr = 1;
	_logoTextShown = false;
}

void Title::revealLogoPixels(Shared::Gfx::GfxSurface &s) {
	// Galois LFSR, polynomial x^17 + x^14 + 1: a maximal-length sequence
	// giving a full-coverage pseudo-random pixel order, replicating the original's fade in
	const uint32 TAP_MASK = (1u << 16) | (1u << 13);
	const int totalPixels = _logo.w * _logo.h;
	Graphics::Surface dest = s.getSubArea(Common::Rect(20, 21, 20 + _logo.w, 21 + _logo.h));

	for (int step = 0; step < LOGO_STEPS_PER_FRAME && _logoPixelsDrawn < totalPixels; ++step) {
		uint32 lsb = _logoLfsr & 1;
		_logoLfsr >>= 1;
		if (lsb)
			_logoLfsr ^= TAP_MASK;

		int pixelIndex = (int)_logoLfsr - 1;
		if (pixelIndex >= 0 && pixelIndex < totalPixels) {
			int x = pixelIndex % _logo.w;
			int y = pixelIndex / _logo.w;
			byte color = *(const byte *)_logo.getBasePtr(x, y);
			*(byte *)dest.getBasePtr(x, y) = color;
			++_logoPixelsDrawn;
		}
	}
}

void Title::drawCreditsLogo(Shared::Gfx::GfxSurface &s) {
	// New lines are revealed from the top (growing downward) and bottom
	// (growing upward) each call, meeting in the middle after
	// CREDITS_LOGO_LINES steps
	for (int i = 0; i < CREDITS_LOGO_STEP && _creditsLine < CREDITS_LOGO_LINES; ++i, ++_creditsLine) {
		int topRow = _creditsLine;
		int bottomRow = _logo.h - 1 - _creditsLine;
		s.blitFrom(_logo, Common::Rect(0, topRow, _logo.w, topRow + 1), Common::Point(20, 21 + topRow));
		s.blitFrom(_logo, Common::Rect(0, bottomRow, _logo.w, bottomRow + 1), Common::Point(20, 21 + bottomRow));
	}
}

void Title::timeout() {
	switch (_state) {
	case PRESENTS:
		if (_logoPixelsDrawn < _logo.w * _logo.h) {
			// Still revealing the logo - keep ticking every frame
			delayFrames(1);
		} else if (!_logoTextShown) {
			// Reveal just finished - hold on the "Presents..." text
			_logoTextShown = true;
			delaySeconds(3);
		} else {
			_state = INTRO_A;
			delaySeconds(4);
		}
		break;
	case INTRO_A:
		_state = INTRO_B;
		delaySeconds(4);
		break;
	case INTRO_B:
		_state = CASTLE;
		_castleStep = 0;
		delayFrames(4);
		break;
	case CASTLE:
		if (++_castleStep >= 100) {
			_state = PRESENTS;
			resetLogoReveal();
			delayFrames(1);
		} else {
			delayFrames(4);
		}
		break;
	case CREDITS:
		if (_creditsLine < CREDITS_LOGO_LINES) {
			// Still sliding the logo in - keep ticking every frame
			delayFrames(1);
		} else if (!_creditsTextShown) {
			// Slide-in just finished - hold on the credits text
			_creditsTextShown = true;
			delaySeconds(3);
		} else {
			showMainMenu();
			return;
		}
		break;
	}

	redraw();
}

void Title::drawCastleFlag(Shared::Gfx::GfxSurface &s, int xp) {
	s.blitFrom(_flags[getRandomNumber(0, 2)], Common::Point(xp, FLAG_Y));
}

void Title::showCredits() {
	_state = CREDITS;
	_creditsLine = 0;
	_creditsTextShown = false;
	redraw();
	delayFrames(1);
}

void Title::showMainMenu() {
	replaceView("MainMenu");
}

bool Title::msgKeypress(const KeypressMessage &msg) {
	if (_state == CREDITS)
		showMainMenu();
	else
		showCredits();
	return true;
}

bool Title::msgMouseDown(const MouseDownMessage &msg) {
	if (_state == CREDITS)
		showMainMenu();
	else
		showCredits();
	return true;
}

bool Title::msgAction(const ActionMessage &msg) {
	if (_state == CREDITS)
		showMainMenu();
	else
		showCredits();
	return true;
}

